import math, sys
# Centre line of the road: a winding S climbing into the distance (108x108 adaptive canvas)
P = [((18,150),(22,96),(82,90),(76,64)), ((76,64),(72,46),(40,52),(46,34))]
def bez(s,t):
    (x0,y0),(x1,y1),(x2,y2),(x3,y3)=s; u=1-t
    return (u**3*x0+3*u*u*t*x1+3*u*t*t*x2+t**3*x3, u**3*y0+3*u*u*t*y1+3*u*t*t*y2+t**3*y3)
pts=[]
for s in P:
    for i in range(60): pts.append(bez(s,i/60))
pts.append(P[-1][3])
# arc length
L=[0]
for i in range(1,len(pts)): L.append(L[-1]+math.dist(pts[i],pts[i-1]))
T=L[-1]
def width(f): return 40*(1-f)**1.3+11*(1-(1-f)**1.3)       # perspective: wide near, narrow far
def normal(i):
    a=pts[max(i-1,0)]; b=pts[min(i+1,len(pts)-1)]; dx,dy=b[0]-a[0],b[1]-a[1]; n=math.hypot(dx,dy); return (-dy/n, dx/n)
def band(i0,i1,scale):
    left=[];right=[]
    for i in range(i0,i1+1):
        nx,ny=normal(i); w=width(L[i]/T)*scale/2; x,y=pts[i]
        left.append((x+nx*w,y+ny*w)); right.append((x-nx*w,y-ny*w))
    return left+right[::-1]
def X(p): return (54+(p[0]-54)*0.84, 59+(p[1]-54)*0.84)
def d(poly): poly=[X(p) for p in poly]; return "M"+" L".join(f"{x:.2f},{y:.2f}" for x,y in poly)+"Z"
shapes=[]
shapes.append(("ridge2","M-10,70 L14,46 L26,56 L44,30 L60,50 L74,38 L96,62 L118,48 L118,120 L-10,120Z"))
shapes.append(("ridge","M-10,82 L20,60 L34,70 L52,52 L70,68 L86,56 L118,80 L118,120 L-10,120Z"))
shapes.append(("edge", d(band(0,len(pts)-1,1.0))))
shapes.append(("asphalt", d(band(0,len(pts)-1,0.78))))
# dashes, getting shorter with distance
f=0.02; i=0
while True:
    seg=0.085*(1-0.6*f); gap=seg*0.8
    a=f; b=f+seg
    if b>0.93: break
    ia=next(k for k in range(len(pts)) if L[k]/T>=a); ib=next(k for k in range(len(pts)) if L[k]/T>=b)
    shapes.append(("dash", d(band(ia,ib,0.09))))
    f=b+gap
# arrowhead at the far end, along the tangent
x,y=pts[-1]; a=pts[-6]; dx,dy=x-a[0],y-a[1]; n=math.hypot(dx,dy); dx/=n; dy/=n; nx,ny=-dy,dx
tip=(x+dx*17,y+dy*17); bl=(x-dx*1+nx*11,y-dy*1+ny*11); br=(x-dx*1-nx*11,y-dy*1-ny*11); notch=(x+dx*4,y+dy*4)
shapes.append(("arrow", d([tip,bl,notch,br])))
colors={"ridge2":"#14283A","ridge":"#101C2A","edge":"#FF9100","asphalt":"#1C2433","dash":"#FFFFFF","arrow":"#00E5FF"}
mode=sys.argv[1]
if mode=="svg":
    print('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="432" height="432">')
    print('<defs><linearGradient id="bg" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#1B3D5C"/><stop offset="1" stop-color="#0B0E14"/></linearGradient><clipPath id="c"><circle cx="54" cy="54" r="%s"/></clipPath></defs>'%sys.argv[2])
    print('<g clip-path="url(#c)"><rect width="108" height="108" fill="url(#bg)"/>')
    for k,p in shapes: print(f'<path d="{p}" fill="{colors[k]}"/>')
    print('</g></svg>')
else:
    head='<?xml version="1.0" encoding="utf-8"?>\n<!-- Curveon icon, %s. Generated by tools/icon/gen.py -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android"%s\n    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">'
    def path(k,p,extra=""): return f'    <path android:fillColor="{colors[k]}"{extra} android:pathData="{p}"/>'
    sh=dict()
    for k,p in shapes: sh.setdefault(k,[]).append(p)
    if mode=="background":
        print(head%("background: night sky over the mountains",'\n    xmlns:aapt="http://schemas.android.com/aapt"'))
        print('    <path android:pathData="M0,0h108v108h-108z">\n        <aapt:attr name="android:fillColor">\n            <gradient android:type="linear" android:startX="54" android:startY="0" android:endX="54" android:endY="108"\n                android:startColor="#1B3D5C" android:endColor="#0B0E14"/>\n        </aapt:attr>\n    </path>')
        for k in ("ridge2","ridge"): print(path(k,sh[k][0]))
    elif mode=="foreground":
        print(head%("foreground: a winding road that turns into a navigation arrow",""))
        for k in ("edge","asphalt","dash","arrow"):
            for p in sh[k]: print(path(k,p))
    elif mode=="companion":
        print(head%("companion foreground: the Curveon road on a phone screen",""))
        phone="M42,29 h24 a6,6 0 0 1 6,6 v38 a6,6 0 0 1 -6,6 h-24 a6,6 0 0 1 -6,-6 v-38 a6,6 0 0 1 6,-6z"
        screen="M42,33 h24 a2,2 0 0 1 2,2 v38 a2,2 0 0 1 -2,2 h-24 a2,2 0 0 1 -2,-2 v-38 a2,2 0 0 1 2,-2z"
        print(f'    <path android:fillColor="#00E5FF" android:fillType="evenOdd" android:pathData="{phone} {screen}"/>')
        print(f'    <group>\n        <clip-path android:pathData="{screen}"/>')
        print(f'        <path android:fillColor="#0B0E14" android:pathData="{screen}"/>')
        print('        <group android:pivotX="54" android:pivotY="54" android:scaleX="0.46" android:scaleY="0.46" android:translateY="1">')
        for k in ("edge","asphalt","dash","arrow"):
            for p in sh[k]: print("    "+path(k,p))
        print('        </group>\n    </group>')
    elif mode=="notification":
        print('<?xml version="1.0" encoding="utf-8"?>\n<!-- Curveon status bar icon. Generated by tools/icon/gen.py -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="24dp" android:height="24dp" android:viewportWidth="72" android:viewportHeight="72">\n    <group android:translateX="-18" android:translateY="-20">')
        print(f'    <path android:fillColor="#FFFFFFFF" android:fillType="evenOdd" android:pathData="{sh["edge"][0]} {sh["asphalt"][0]}"/>')
        for k in ("dash","arrow"):
            for p in sh[k]: print(f'    <path android:fillColor="#FFFFFFFF" android:pathData="{p}"/>')
        print('    </group>')
    else:
        print(head%("monochrome layer for themed icons",""))
        print(f'    <path android:fillColor="#FFFFFFFF" android:fillType="evenOdd" android:pathData="{sh["edge"][0]} {sh["asphalt"][0]}"/>')
        for k in ("dash","arrow"):
            for p in sh[k]: print(f'    <path android:fillColor="#FFFFFFFF" android:pathData="{p}"/>')
    print('</vector>')
